// Test de la fenêtre du bureau de change (Chromium, sans internet) : NODE_PATH=$(npm root -g) node tests/ui_change.cjs
const { chromium } = require('playwright');
const path = require('path');
const shots = process.env.SHOTS || require('os').tmpdir();
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
  const errs = [], ext = [];
  p.on('pageerror', (e) => errs.push(e.message));
  await p.route('**/*', (r) => { const u = r.request().url(); if (u.startsWith('file:')) return r.continue(); ext.push(u); return r.abort(); });
  await p.addInitScript(() => {
    window.__calls = [];
    window.GetParentResourceName = () => 'elyzea_change';
    window.fetch = (url, o) => { window.__calls.push([String(url).split('/').pop(), JSON.parse((o && o.body) || '{}')]); return Promise.resolve({ json: () => Promise.resolve(true) }); };
  });
  await p.goto('file://' + path.join(__dirname, '..', 'html', 'index.html'));
  let fails = 0;
  const check = async (label, fn) => { const r = await p.evaluate(fn); if (r !== true) fails++; console.log((r === true ? 'OK  ' : 'FAIL') + ' ' + label + (r === true ? '' : ' -> ' + JSON.stringify(r))); };
  const post = (m) => p.evaluate((m) => window.postMessage(m, '*'), m);
  await post({ action: 'open', data: { name: 'Change du port', toPesos: 100, toCash: 90, min: 1, max: 1000000, money: { cash: 2500, pesos: 300 } } });
  await p.waitForTimeout(250);
  await check('fenêtre ouverte, soldes affichés', () => document.querySelector('#panel').classList.contains('open') && document.querySelector('#cash').textContent.includes('2') && document.querySelector('#pesos').textContent === '300');
  await check('pièce Cayo Perico affichée', () => { const i = document.querySelector('.head img'); return i.complete && i.naturalWidth > 0; });
  await p.fill('#amount', '1000');
  await check('aperçu : 1 000 $ → 1 000 pesos', () => document.querySelector('#out').textContent.replace(/\s/g, '') === '1000pesos');
  await p.screenshot({ path: path.join(shots, 'ui_change.png') });
  await p.click('#go'); await p.waitForTimeout(100);
  await check('demande envoyée (sens, montant, numéro unique)', () => { const c = window.__calls.find((x) => x[0] === 'convert'); return !!c && c[1].dir === 'buy' && c[1].amount === 1000 && c[1].nonce.length > 4; });
  await check('bouton bloqué pendant le change (pas de double clic)', () => document.querySelector('#go').disabled);
  await post({ action: 'result', ok: true, text: 'Change effectué : 1000 $ → 1000 pesos.', money: { cash: 1500, pesos: 1300 } }); await p.waitForTimeout(100);
  await check('résultat : soldes à jour, message vert', () => document.querySelector('#pesos').textContent.replace(/\s/g, '') === '1300' && document.querySelector('#msg').classList.contains('ok'));
  await p.click('#dir button[data-d="sell"]');
  await p.click('.quick button[data-q="all"]');
  await check('Pesos → $ : « Tout » = 1 300 pesos → 1 170 $', () => document.querySelector('#amount').value === '1300' && document.querySelector('#out').textContent.replace(/\s/g, '') === '1170$');
  await p.fill('#amount', '5000');
  await check('plus que le solde : bouton « Solde insuffisant » bloqué', () => document.querySelector('#go').disabled && document.querySelector('#go').textContent.includes('insuffisant'));
  await p.fill('#amount', '1');
  await check('1 peso → 0 $ : bloqué', () => document.querySelector('#go').disabled);
  await post({ action: 'result', ok: false, text: 'Approche-toi du guichet.', money: { cash: 1500, pesos: 1300 } }); await p.waitForTimeout(80);
  await check('erreur affichée en rouge', () => document.querySelector('#msg').classList.contains('err'));
  await p.keyboard.press('Escape'); await p.waitForTimeout(150);
  await check('Échap : fermé, le jeu est prévenu', () => !document.querySelector('#panel').classList.contains('open') && window.__calls.some((x) => x[0] === 'close'));
  await p.setViewportSize({ width: 380, height: 700 });
  await post({ action: 'open', data: { name: 'Change', toPesos: 100, toCash: 100, min: 1, max: 1000000, money: { cash: 1, pesos: 1 } } }); await p.waitForTimeout(250);
  await check('petit écran : fenêtre dans l\'écran', () => { const r = document.querySelector('#panel').getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth; });
  if (ext.length) { fails++; console.log('FAIL requêtes externes : ' + ext.join(', ')); } else console.log('OK   aucune requête vers internet');
  if (errs.length) { fails++; console.log('FAIL erreurs JS : ' + errs.join(' | ')); } else console.log('OK   aucune erreur JS');
  console.log(`\n${fails} échec(s)`);
  await b.close(); process.exit(fails ? 1 : 0);
})();
