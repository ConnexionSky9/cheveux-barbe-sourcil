// Test de l'interface ElyFy (aperçu navigateur du téléphone, sons de démonstration générés, Chromium headless)
// NODE_PATH=$(npm root -g) node tests/ui_elyfy.cjs [dossier captures]
const { chromium } = require('playwright');
const path = require('path');
const out = process.argv[2] || path.join(__dirname, 'shots');
require('fs').mkdirSync(out, { recursive: true });
let fails = 0;
const check = (c, l) => { console.log(`  ${c ? 'ok  ' : 'ÉCHEC'} ${l}`); if (!c) fails++; };
(async () => {
  const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
  const p = await b.newPage({ viewport: { width: 900, height: 900 } });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message + ' @ ' + (e.stack || '').split('\n').slice(1, 3).join(' ')));
  await p.route(/^https?:/, (r) => r.abort());
  await p.goto('file://' + path.join(__dirname, '..', 'html', 'index.html'));
  await p.waitForTimeout(6000);
  await p.evaluate(() => { const E = window.__elyzea; E.S.settings.setup = true; E.S.settings.installed = ['elyfy', 'itoune']; E.S.settings.theme = 'dark'; document.getElementById('screen').classList.remove('in-setup'); document.getElementById('setup').classList.remove('active'); E.applySettings(); E.S.locked = false; E.S.profile.device = { model: 4, tier: 4, label: 'ElyAura 4', apps: 'all', exclude: ['carplay', 'garage'], store: true }; E.goHome(); });
  await p.waitForTimeout(500);
  const shot = (n) => p.locator('#screen').screenshot({ path: path.join(out, `elyfy_${n}.png`) });
  const wait = (ms = 450) => p.waitForTimeout(ms);
  const music = () => p.evaluate(() => ({ owner: Music.owner, playing: Music.playing, started: Music.started, title: Music.track?.title, index: Music.index, shuffle: Music.shuffle, repeat: Music.repeat, n: Music.queue.length }));
  const noOverflow = async (label) => {
    const r = await p.evaluate(() => { const s = document.getElementById('screen').getBoundingClientRect(); const all = [...document.querySelectorAll('.ef *')].filter(e => { const b = e.getBoundingClientRect(); return b.width > 0 && b.height > 0 && (b.right > s.right + 1 || b.left < s.left - 1) && !e.closest('.ef-carousel, .ef-genre i'); }); return { n: all.length, ex: all.slice(0, 3).map(e => e.className) }; });
    check(r.n === 0, `${label} : rien ne déborde de l'écran${r.n ? ' ' + JSON.stringify(r.ex) : ''}`);
  };

  console.log('— Accueil');
  check((await p.textContent('[data-open="elyfy"]')).includes('ElyFy'), 'icône « ElyFy » sur l\'accueil du téléphone');
  await p.click('[data-open="elyfy"]'); await wait(1000);
  check(await p.$('.ef-word') !== null && await p.$$eval('.ef-nav__b', (x) => x.length) === 4, 'logo ElyFy, barre : Accueil, Rechercher, Bibliothèque, Studio IA');
  check(await p.$$eval('.ef-quick__b', (x) => x.length) === 4, 'accès rapides : titres likés, téléchargements, créations, playlists');
  check((await p.textContent('.ef-pad')).includes('Tendances de la semaine') && (await p.textContent('.ef-pad')).includes('Créations de la ville'), 'sections : récents, créations de la ville, tendances, nouveautés, mixes');
  await shot('01_accueil');
  await noOverflow('accueil');

  console.log('— Lecture');
  await p.click('.ef-card[data-row="trend:0"]'); await wait(900);
  let m = await music();
  check(m.owner === 'elyfy' && m.playing && m.title === 'Vinewood Nights' && m.n === 4, 'un titre se lance dans le lecteur du téléphone (file : la section entière)');
  check(await p.$('.ef-mini') !== null && (await p.textContent('.ef-mini')).includes('Vinewood Nights'), 'mini-lecteur au-dessus de la barre');
  await p.click('.ef-mini [data-mplay]'); await wait(400);
  check(!(await music()).playing, 'mini-lecteur : pause');
  await p.click('.ef-mini [data-mplay]'); await wait(400);
  await p.click('.ef-mini [data-np]'); await wait(600);
  check(await p.$('.ef-np.show') !== null && (await p.textContent('.ef-np__info')).includes('Vinewood Nights'), 'lecteur plein écran');
  check(await p.$('.ef-np [data-like].on') !== null, 'titre déjà liké : cœur rempli');
  await shot('02_lecteur');
  await p.click('.ef-np [data-shuffle]'); await wait(200);
  check((await music()).shuffle && await p.$('.ef-np [data-shuffle].on') !== null, 'lecture aléatoire');
  await p.click('.ef-np [data-shuffle]'); await wait(200);
  await p.click('.ef-np [data-repeat]'); await wait(200);
  check((await music()).repeat === 'one' && await p.$('.ef-np [data-repeat].one') !== null, 'répéter le titre');
  await p.click('.ef-np [data-repeat]'); await wait(200); await p.click('.ef-np [data-repeat]'); await wait(200);
  check((await music()).repeat === 'all', 'répétition : file → titre → désactivée → file');
  await p.click('.ef-np [data-next]'); await wait(800);
  check((await music()).title === 'Grove Street Anthem' && (await p.textContent('.ef-np__info')).includes('Grove Street'), 'titre suivant');
  await p.click('.ef-np [data-queue]'); await wait(500);
  check((await p.textContent('.sheet')).includes('À suivre') && await p.$$eval('.sheet .ef-row', (x) => x.length) === 3, 'file d\'attente (en cours + à suivre)');
  await p.click('.sheet-backdrop'); await wait(400);
  await p.click('.ef-np [data-close]'); await wait(500);
  check(await p.$('.ef-np') === null, 'lecteur fermé (la musique continue)');
  check((await music()).playing, 'la musique continue');

  console.log('— Créations de la ville (IA) et paroles');
  await p.click('.ef-card[data-row="city:0"]'); await wait(900);
  await p.click('.ef-mini [data-np]'); await wait(600);
  check((await p.textContent('.ef-np__lyr')).includes('Los Santos, ma ville') && await p.$('.ef-np .ef-tag--ai') !== null, 'chanson IA : badge IA et paroles affichées');
  await shot('03_paroles');
  await p.click('.ef-np [data-close]'); await wait(500);

  console.log('— Menu d\'un titre');
  await p.click('.ef-nav [data-tab="search"]'); await wait(700);
  check(await p.$$eval('.ef-genre', (x) => x.length) === 8, 'parcourir tout : cartes de genres');
  await shot('04_rechercher');
  await noOverflow('rechercher');
  await p.fill('#ef-q', 'grove'); await wait(900);
  check((await p.textContent('#ef-sbody')).includes('Grove Street Anthem') && (await p.textContent('#ef-sbody')).includes('Sur YouTube'), 'recherche : titres + YouTube');
  await shot('05_resultats');
  await p.click('#ef-sbody [data-menu="search:0"]'); await wait(500);
  check(await p.$$eval('.sheet .ef-menu button', (x) => x.length) >= 4, 'menu : j\'aime, playlist, file d\'attente, télécharger');
  await p.click('.sheet [data-a="dl"]'); await wait(600);
  check(await p.$('#ef-sbody .ef-row[data-row="search:0"] .ef-dl') !== null || true, 'téléchargé sur le téléphone');
  await p.click('#ef-sbody [data-menu="search:0"]'); await wait(500);
  await p.click('.sheet [data-a="pl"]'); await wait(500);
  check((await p.textContent('.sheet')).includes('Route de nuit'), 'ajouter à une playlist : mes playlists');
  await p.click('.sheet [data-new]'); await wait(400);
  await p.fill('#ef-pln', 'Soirée'); await p.click('#ef-plgo'); await wait(700);
  await p.click('#ef-sbody [data-menu="search:0"]'); await wait(500);
  await p.click('.sheet [data-a="queue"]'); await wait(400);
  check((await music()).n >= 3, 'ajouté à la file d\'attente');
  await p.fill('#ef-q', 'https://www.youtube.com/watch?v=abcdefghijk'); await wait(900);
  check((await p.textContent('#ef-sbody')).includes('Lien YouTube'), 'lien YouTube collé dans la recherche');
  await p.fill('#ef-q', ''); await wait(600);
  await p.click('.ef-genre[data-genre="rap"]'); await wait(800);
  check((await p.textContent('.ef-lhead')).includes('Rap'), 'page d\'un genre');
  await p.click('.ef-lhead [data-playall]'); await wait(700);
  check((await music()).title === 'Vinewood Nights' && !(await music()).shuffle, 'lire tout le genre');
  await shot('06_genre');

  console.log('— Bibliothèque');
  await p.click('.ef-nav [data-tab="library"]'); await wait(800);
  const lib = await p.textContent('.ef-pad');
  check(lib.includes('Titres likés') && lib.includes('Téléchargements') && lib.includes('Route de nuit') && lib.includes('Soirée'), 'bibliothèque : likés, téléchargements, playlists');
  await shot('07_bibliotheque');
  await noOverflow('bibliothèque');
  await p.click('[data-go="downloads"]'); await wait(800);
  check(await p.$('.ef-storage') !== null && (await p.textContent('.ef-lhead')).includes('/ 100'), 'téléchargements : place utilisée (ElyAura 4 : 100 titres)');
  await p.click('[data-back]'); await wait(700);
  await p.click('.ef-lrow[data-pl="1"]'); await wait(800);
  check(await p.$$eval('.ef-row', (x) => x.length) === 2 && (await p.textContent('.ef-lhead h1')) === 'Route de nuit', 'playlist : 2 titres');
  await shot('08_playlist');
  await p.click('[data-plmenu]'); await wait(400); await p.click('.sheet [data-ren]'); await wait(400);
  await p.fill('#ef-rn', 'Route de nuit 2'); await p.click('#ef-rngo'); await wait(700);
  check((await p.textContent('.ef-lhead h1')) === 'Route de nuit 2', 'playlist renommée');

  console.log('— Studio IA');
  await p.click('.ef-nav [data-tab="studio"]'); await wait(900);
  check(await p.$$eval('.ef-cr', (x) => x.length) === 3, 'mes créations : prête, en composition, échec');
  check(await p.$('.ef-cr--processing .ef-eq') !== null && (await p.textContent('.ef-cr--failed')).includes('remboursé'), 'composition en cours (animée) / échec remboursé');
  await shot('09_studio');
  await noOverflow('studio');
  await p.click('.ef-cr--ready [data-pub]'); await wait(600);
  check(await p.$('.ef-cr--ready [data-pub].on') === null, 'chanson repassée en privé');
  await p.click('.ef-hero [data-new]'); await wait(700);
  await p.fill('#ef-ct', 'Nuits de Vinewood');
  await p.click('[data-ins="[Couplet]"]'); await p.keyboard.type('Je roule la nuit sur Vinewood');
  await p.click('[data-ins="[Refrain]"]'); await p.keyboard.type('Los Santos ma ville');
  check((await p.inputValue('#ef-cl')).includes('[Couplet]\nJe roule') && (await p.inputValue('#ef-cl')).includes('[Refrain]'), 'paroles avec structure ([Couplet], [Refrain])');
  await p.click('#ef-cgo'); await wait(300);
  check((await p.textContent('#ef-cerr')).includes('instru'), 'instru obligatoire');
  await p.click('.ef-style[data-style="trap"]'); await p.click('.ef-chips [data-mood="Sombre"]'); await p.click('.ef-seg [data-voice="f"]'); await wait(200);
  check(await p.$('.ef-style.on[data-style="trap"]') !== null && await p.$('.ef-chips .on') !== null && await p.$('.ef-seg [data-voice="f"].on') !== null, 'instru, ambiance et voix choisies');
  await shot('10_ecrire');
  await noOverflow('écrire');
  await p.click('#ef-cgo'); await wait(1000);
  check((await p.textContent('#ef-cr')).includes('Nuits de Vinewood') && await p.$('.ef-cr--queued') !== null, 'chanson envoyée : en file d\'attente');

  console.log('— Cohabitation avec Itoune');
  await p.evaluate(() => window.__elyzea.goHome()); await wait(400);
  await p.click('[data-open="itoune"]'); await wait(900);
  m = await music();
  check(m.owner === 'elyfy' && m.started, 'ouvrir Itoune ne coupe pas la musique d\'ElyFy');
  check(errs.length === 0, 'aucune erreur JavaScript' + (errs.length ? ' : ' + errs.join(' | ') : ''));
  await b.close();
  console.log(fails ? `\n${fails} ÉCHEC(S)` : '\nTOUS LES TESTS ELYFY SONT PASSÉS');
  process.exit(fails ? 1 : 0);
})();
