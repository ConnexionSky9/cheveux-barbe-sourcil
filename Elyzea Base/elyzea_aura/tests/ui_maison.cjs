// Test de l'appli MAISON (aperçu navigateur du téléphone, données de démonstration, Chromium headless)
// NODE_PATH=$(npm root -g) node tests/ui_maison.cjs [dossier captures]
const { chromium } = require('playwright');
const path = require('path');
const out = process.argv[2] || path.join(__dirname, 'shots');
require('fs').mkdirSync(out, { recursive: true });
let fails = 0;
const check = (c, l) => { console.log(`  ${c ? 'ok  ' : 'ÉCHEC'} ${l}`); if (!c) fails++; };
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 900, height: 900 }, deviceScaleFactor: 2 });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  const posts = [], calls = [];
  await p.route(/^https?:/, (r) => r.abort());
  await p.goto('file://' + path.join(__dirname, '..', 'html', 'index.html'));
  await p.waitForTimeout(6000);
  await p.exposeFunction('__post', (ep, d) => posts.push({ ep, d }));
  await p.exposeFunction('__call', (d) => calls.push(d));
  await p.evaluate(() => { const M = window.__elyzea.Mock, h = M.handle.bind(M);
    M.handle = (ep, d) => { if (ep !== 'request') window.__post(ep, d); else if (d.name === 'maisonCall') window.__call(d.args); return h(ep, d); }; });
  await p.evaluate(() => { const E = window.__elyzea; E.S.settings.setup = true; E.S.settings.theme = 'dark'; document.getElementById('screen').classList.remove('in-setup'); document.getElementById('setup').classList.remove('active'); E.applySettings(); E.S.locked = false; E.S.maisonHas = false; E.goHome(); });
  await p.waitForTimeout(300);
  check(await p.$('[data-open="maison"]') === null, 'sans logement : pas d\'icône Maison');
  await p.evaluate(() => mzCheckHas()); await p.waitForTimeout(400);
  check((await p.textContent('[data-open="maison"]')).includes('Maison'), 'avec un logement : icône « Maison » sur l\'accueil');
  await p.locator('#screen').screenshot({ path: path.join(out, 'maison_00_accueil_tel.png') });
  await p.click('[data-open="maison"]'); await p.waitForTimeout(800);
  const shot = (n) => p.locator('#screen').screenshot({ path: path.join(out, `maison_${n}.png`) });
  check(await p.$$eval('.mz-card', (x) => x.length) === 2, 'accueil : mes 2 logements');
  check((await p.textContent('.mz-card')).includes('Titulaire') && (await p.textContent('.mz-card:nth-of-type(1)')).includes('Villa'), 'carte : nom, rôle');
  check(await p.$('.mz-bell') !== null && (await p.textContent('.mz-bell')).includes('Malik'), 'sonnette en attente avec le nom du visiteur');
  await shot('01_accueil');
  await p.selectOption('.mz-bell [data-bell-min]', '60');
  await p.click('.mz-bell [data-bell-yes]'); await p.waitForTimeout(400);
  const ba = calls.find((c) => c.action === 'bellAnswer');
  check(ba && ba.data.accept === true && ba.data.minutes === 60, 'ouvrir à distance pour 60 min');
  await p.click('.mz-card[data-prop="1"]'); await p.waitForTimeout(800);
  check(await p.$$eval('.mz-tabs button', (x) => x.length) === 4, 'fiche : Aperçu, Surveillance, Services, Gestion');
  check(await p.$('[data-buy="cannabis"]') !== null, 'amélioration non achetée : bouton Acheter');
  await shot('02_apercu');
  await p.click('[data-buy="cannabis"]'); await p.waitForTimeout(500);
  await p.click('[data-pay="bank"]'); await p.waitForTimeout(500);
  check(calls.some((c) => c.action === 'buy' && c.data.kind === 'cannabis' && c.data.method === 'bank'), 'achat par carte envoyé au serveur');
  await p.click('[data-mz-tab="surv"]'); await p.waitForTimeout(600);
  check(await p.$$eval('.mz-cam', (x) => x.length) === 2, 'surveillance : 2 caméras');
  await p.click('[data-cam-view="1"]'); await p.waitForTimeout(900);
  check(await p.$('#mz-live:not(.hidden) canvas') !== null, 'image en direct affichée dans l\'écran');
  check(posts.some((x) => x.ep === 'maisonCam' && x.d.op === 'start' && x.d.idx === 1), 'caméra 1 demandée au jeu');
  check((await p.textContent('#mz-camname')).includes('Entrée'), 'nom de la caméra affiché');
  await shot('03_direct');
  await p.click('[data-cam-next]'); await p.waitForTimeout(300);
  check(posts.some((x) => x.ep === 'maisonCam' && x.d.op === 'set' && x.d.idx === 2) && (await p.textContent('#mz-camname')).includes('Jardin'), 'caméra suivante');
  await p.click('[data-cam-quit]'); await p.waitForTimeout(300);
  check(posts.some((x) => x.ep === 'maisonCam' && x.d.op === 'stop') && await p.$('#mz-live.hidden') !== null, 'quitter le direct');
  await p.click('[data-cam-place]'); await p.waitForTimeout(500);
  check(posts.some((x) => x.ep === 'maisonPlaceCam' && x.d.pid === 1), 'installer une caméra : le téléphone lance la pose');
  await p.click('[data-mz-tab="svc"]'); await p.waitForTimeout(600);
  await p.selectOption('#mz-anim', 'lapdance'); await p.selectOption('#mz-dur', '15');
  await p.click('[data-dn="start"]'); await p.waitForTimeout(500);
  check(calls.some((c) => c.action === 'dancerStart' && c.data.anim === 'lapdance' && c.data.minutes === 15), 'danseuse : animation et durée envoyées');
  await shot('04_services');
  await p.click('[data-mz-tab="mng"]'); await p.waitForTimeout(600);
  check(await p.$('#mz-code') !== null && await p.$$eval('.mz-person', (x) => x.length) === 1 && await p.$$eval('.mz-tenant', (x) => x.length) === 1, 'gestion : code, visiteurs, locataires');
  await shot('05_gestion');
  await p.fill('#mz-code', '7788'); await p.click('[data-code="set"]'); await p.waitForTimeout(400);
  check(calls.some((c) => c.action === 'setCode' && c.data.code === '7788'), 'code envoyé');
  await p.check('.mz-tenant [data-tr="dancer"]'); await p.waitForTimeout(400);
  const ts = calls.filter((c) => c.action === 'tenantSet').pop();
  check(ts && ts.data.dancer === true && ts.data.stash === true && ts.data.cid === 'AB1', 'droits du locataire envoyés');
  await p.fill('#mz-inv', '14'); await p.click('[data-invite]'); await p.waitForTimeout(400);
  check(calls.some((c) => c.action === 'grantInvite' && c.data.target === 14), 'autoriser un joueur par ID');
  const over = await p.evaluate(() => { const s = document.getElementById('screen').getBoundingClientRect(); return [...document.querySelectorAll('.mz *')].filter((e) => { const r = e.getBoundingClientRect(); return r.width > 0 && (r.right > s.right + 1 || r.left < s.left - 1); }).length; });
  check(over === 0, 'rien ne déborde de l\'écran');
  check(errs.length === 0, 'aucune erreur JavaScript' + (errs.length ? ' : ' + errs.join(' | ') : ''));
  await b.close();
  console.log(fails ? `${fails} ÉCHEC(S)` : 'TOUS LES TESTS MAISON SONT PASSÉS');
  process.exit(fails ? 1 : 0);
})();
