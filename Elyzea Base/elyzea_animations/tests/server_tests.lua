-- =====================================================================
--  Tests serveur hors jeu (voir run_tests.py) : danses en duo, en groupe, animations partagées.
--  Chaque test part d'un état neuf : joueurs 1, 2, 3 et 4 proches les uns des autres.
-- =====================================================================
Tests = {}
local function T(name, fn) Tests[#Tests + 1] = { name = name, fn = fn } end
local function check(cond, msg) if not cond then error(msg or 'vérification échouée', 2) end end
local function count(name, target) return #Mock.Sent(name, target) end
local function lastNotify(target)
    local l = Mock.Sent('elyzea_danse:cl:notify', target)
    return l[#l] and l[#l].args[1] or ''
end
local function inviteId(target)
    local l = Mock.Sent('elyzea_danse:cl:invite', target)
    return l[#l] and l[#l].args[1].id
end
local function setup()
    Mock.AddPlayer(1, 0, 0)
    Mock.AddPlayer(2, 1.5, 0)
    Mock.AddPlayer(3, 0, 1.5)
    Mock.AddPlayer(4, -1.5, 0)
    Mock.Advance(100)
end
local function invite(from, to, anim, role) Mock.Call(from, 'elyzea_danse:sv:invite', to, anim or 'slow_face', role or 'A') end
local function respond(src, id, accept) Mock.Call(src, 'elyzea_danse:sv:respond', id, accept) end
local function group(host, targets, anim, formation) Mock.Call(host, 'elyzea_danse:sv:group', anim or 'groupe_thriller', formation or 'ligne', targets) end
local function sessionOf(id) return Danse.Sessions.Of(id) end
local function readyAll(s) for _, p in ipairs(s.members) do Mock.Call(p, 'elyzea_danse:sv:ready', s.id, true) end end
local function wait() Mock.Advance(DanseConfig.Invite.Cooldown * 1000 + 50) Mock.Clear() end

-- ── Duo ───────────────────────────────────────────────────────────────────
T('Duo accepté : session, rôles, partenaire connu des deux, départ après « prêt » des deux', function()
    setup()
    invite(1, 2)
    local id = inviteId(2)
    check(id, 'invitation reçue')
    respond(2, id, true)
    local s = sessionOf(1)
    check(s and s == sessionOf(2) and s.anchor == 1, 'session, meneur = auteur')
    local p1, p2 = Mock.Sent('elyzea_danse:cl:prepare', 1)[1].args[1], Mock.Sent('elyzea_danse:cl:prepare', 2)[1].args[1]
    check(p1.slot == 0 and p2.slot == 1, 'places')
    check(p1.partner == 2 and p2.partner == 1, 'chacun connaît son partenaire')
    Mock.Call(1, 'elyzea_danse:sv:ready', s.id, true)
    check(count('elyzea_danse:cl:go') == 0, 'pas de départ avec un seul prêt')
    Mock.Call(2, 'elyzea_danse:sv:ready', s.id, true)
    check(count('elyzea_danse:cl:go', 1) == 1 and count('elyzea_danse:cl:go', 2) == 1, 'départ commun')
end)

