T('Anti-spam : délai entre invitations et limite par minute', function()
    setup()
    invite(1, 2)
    Mock.Clear()
    invite(1, 3)
    check(not inviteId(3), 'délai entre deux invitations')
    check(lastNotify(1):find('Attends'), 'message de délai')
    -- Groupes créés puis annulés en boucle, toutes les 5 s : la limite par minute doit bloquer
    local sent = 0
    for _ = 1, 11 do
        Mock.Advance(DanseConfig.Invite.Cooldown * 1000 + 50)
        Mock.Clear()
        group(4, { 3 })
        if inviteId(3) then sent = sent + 1 end
        Mock.Call(4, 'elyzea_danse:sv:stop', 'stop')
    end
    check(sent >= 1 and sent <= DanseConfig.Invite.MaxPerMinute - 0, 'groupes envoyés en une minute : ' .. sent)
    check(sent < 11, 'la limite doit bloquer des envois')
end)

