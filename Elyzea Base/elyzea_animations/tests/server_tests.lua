    for i = 1, 48 do Mock.Drop(i) end
    check(next(Danse.Sessions.list) == nil and next(Danse.Sessions.of) == nil, 'sessions nettoyées')
    check(next(Danse.Invites.list) == nil and next(Danse.Lobbies.list) == nil and next(Danse.Lobbies.of) == nil, 'invitations et groupes nettoyés')
