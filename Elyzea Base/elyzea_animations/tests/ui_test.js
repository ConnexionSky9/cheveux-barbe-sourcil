const { chromium } = require('playwright');
const fs = require('fs');
const [S, HTML] = process.argv.slice(2);
const danses = JSON.parse(fs.readFileSync(S + '/k_danses.json', 'utf8'));
const env = JSON.parse(fs.readFileSync(S + '/k_env.json', 'utf8'));
const out = []; const ok = (n, c) => out.push((c ? 'RÉUSSI  ' : 'ÉCHEC   ') + n);
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1600, height: 900 } });
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.addInitScript(() => {
    window.GetParentResourceName = () => 'elyzea_animations'; window.__posts = [];
    const of = window.fetch;
    window.fetch = (u, o) => {
      if (String(u).startsWith('https://elyzea_animations/')) {
        const name = String(u).split('/').pop(); const data = o && o.body ? JSON.parse(o.body) : {};
        window.__posts.push({ name, data });
        if (name === 'getNearbyPlayers') return Promise.resolve(new Response(JSON.stringify([{ id: 2, name: 'Joueur 2', dist: 1.4 }, { id: 3, name: 'Joueur 3', dist: 5.2 }])));
        return Promise.resolve(new Response('true'));
      }
      return of(u, o);
    };
  });
  await p.goto('file://' + HTML);
  await p.evaluate(m => window.postMessage(m, '*'), danses);
  await p.evaluate(m => window.postMessage(m, '*'), { action: 'init', settings: {}, binds: {}, keys: { accept: 'Y', refuse: 'L', place: 'J' } });
  await p.evaluate(m => window.postMessage(m, '*'), env);
  await p.evaluate(() => window.postMessage({ action: 'open' }, '*'));
  await p.waitForTimeout(400);
  const rail = await p.$$eval('#rail .cat', n => n.map(x => x.dataset.id));
  ok('Ordre du menu : Favoris, Récents, Lentes, Duo, Groupe, Solo puis le reste : ' + rail.slice(0, 7).join(','),
     rail.slice(0, 6).join(',') === 'fav,recent,d_lentes,d_duo,d_groupe,danses');
  ok('Aucun bouton ou menu séparé pour les danses', !(await p.$('[data-id="__dances"]')));
  await p.click('[data-id="d_lentes"]');
  await p.waitForTimeout(150);
  const lentes = await p.$$eval('#grid .emote b', n => n.map(x => x.textContent));
  ok('Danses lentes : ' + lentes.join(' | '), lentes.length >= 5 && lentes.includes('Slow enlacé face à face'));
  await p.screenshot({ path: S + '/k2_lentes.png' });
  await p.click('#grid .emote[data-cmd="danse:slow_face"]');
  await p.waitForTimeout(300);
  ok('Clic sur un slow : choix du partenaire avec choix du rôle', await p.isVisible('#picker.open') && await p.isVisible('#pickRole'));
  await p.click('#pickRole [data-role="B"]');
  await p.screenshot({ path: S + '/k2_picker.png' });
  await p.click('#pickList .player[data-pid="2"]');
  await p.waitForTimeout(150);
  let posts = await p.evaluate(() => window.__posts);
  const inv = posts.find(x => x.name === 'playEmote');
  ok('Invitation duo envoyée : cible 2, rôle B', inv && inv.data.emote === 'danse:slow_face' && inv.data.target === 2 && inv.data.role === 'B' && inv.data.type === 'danse_duo');
  await p.click('[data-id="d_groupe"]');
  await p.click('#grid .emote[data-cmd="danse:groupe_thriller"]');
  await p.waitForTimeout(300);
  ok('Clic sur une danse de groupe : choix de plusieurs participants et de la formation', await p.isVisible('#groupBox') && !(await p.isVisible('#pickRole')));
  ok('Bouton Inviter désactivé sans participant', await p.isDisabled('#groupGo'));
  await p.click('#pickList .player[data-pid="2"]'); await p.click('#pickList .player[data-pid="3"]');
  await p.click('#groupForms [data-form="cercle"]');
  await p.screenshot({ path: S + '/k2_groupe.png' });
  await p.click('#groupGo');
  posts = await p.evaluate(() => window.__posts);
  const g = posts.find(x => x.name === 'danseGroup');
  ok('Groupe envoyé : 2 participants, en cercle', g && g.data.id === 'groupe_thriller' && g.data.targets.length === 2 && g.data.formation === 'cercle');
  await p.click('[data-id="danses"]');
  const solo = await p.$$eval('#grid .emote', n => n.length);
  const head = await p.textContent('#catTitle');
  ok('Danses solo (sans doublons) : ' + solo + ' danses, titre « ' + head + ' »', head.trim() === 'Danses solo' && solo > 90 && solo < 115);
  await p.fill('#q', 'slow');
  await p.waitForTimeout(150);
  const found = await p.$$eval('#grid .emote b', n => n.map(x => x.textContent));
  ok('Recherche « slow » trouve les slows : ' + found.slice(0, 5).join(' | '), found.includes('Slow enlacé face à face') && found.includes('Slow tournant'));
  await p.fill('#q', '');
  await p.evaluate(() => window.postMessage({ action: 'request', name: 'Une personne (ID 2)', label: 'Slow face à face', timeout: 20 }, '*'));
  await p.waitForTimeout(200);
  ok('Invitation reçue : fenêtre Accepter / Refuser du menu K', await p.isVisible('#req.show'));
  await p.evaluate(() => window.postMessage({ action: 'playing', label: 'Slow face à face' }, '*'));
  ok('Barre « En cours »', (await p.textContent('#now')).includes('Slow face à face'));
  await p.evaluate(() => window.postMessage({ action: 'stopped' }, '*'));
  ok('Arrêt affiché', (await p.textContent('#now')).trim() === '');
  ok('Aucune erreur JavaScript', errs.length === 0);
  if (errs.length) console.log(errs.join('\n'));
  console.log(out.join('\n'));
  await b.close();
})();
