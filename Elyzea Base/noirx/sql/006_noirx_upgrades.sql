CREATE TABLE IF NOT EXISTS `noirx_upgrades` (
  `char_id` VARCHAR(64) NOT NULL,
  `police_radius` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `defense_level` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `reveal_level` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `intel_level` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`char_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
