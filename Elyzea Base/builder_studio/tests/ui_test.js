// Pilote l'interface dans Chromium : erreurs JS, rappels NUI envoyés, captures d'écran
const { chromium } = require('playwright');
const fs = require('fs');
const [, , page_, dataPath, out] = process.argv;
const data = JSON.parse(fs.readFileSync(dataPath, 'utf8'));
let fails = 0;
const ok = (c, m) => { console.log((c ? '  ok   ' : '  ÉCHEC ') + m); if (!c) fails++; };
(async () => {
    const browser = await chromium.launch();
    const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
    const errors = [];
    page.on('pageerror', (e) => errors.push(e.message));
    page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
    await page.addInitScript(() => {
        window.__posts = [];
        window.DemoPost = (name, d) => {
            window.__posts.push({ name, d });
            if (name === 'checkModels') { const o = {}; (d.models || []).forEach((m, i) => { o[m] = i % 9 !== 0; }); return { ok: true, models: o }; }
            if (name === 'kitStatus') return { ok: true, kits: { ubk: { present: 0, total: 337 }, blocs: { present: 4, total: 4 } }, ubkMaterials: {} };
            if (name === 'prefs:get') return { ok: true, fav: ['prop_bench_01a'], recent: [] };
            if (name === 'terrainHeights') return { ok: true, heights: new Array(d.cols * d.rows).fill(1) };
            return { ok: true };
        };
    });
    await page.goto('file://' + page_);
    await page.evaluate((d) => window.postMessage({ action: 'open', ...d.init }, '*'), data);
    await page.waitForTimeout(300);
    ok(await page.isVisible('#app'), 'interface ouverte');
    ok(await page.isVisible('#modal') && (await page.textContent('#modalTitle')).includes('projets'), 'gestionnaire de projets affiché');
    await page.screenshot({ path: out + '/ui_accueil.png' });
    await page.click('#homeCreate');
    ok((await page.evaluate(() => __posts.map((p) => p.name))).includes('project:create'), 'création de projet envoyée');
    await page.evaluate((d) => window.postMessage({ action: 'project', project: d.project }, '*'), data);
    await page.waitForTimeout(200);
    ok(!(await page.isVisible('#modal')), 'gestionnaire fermé à l\'ouverture du projet');
    const nodes = await page.$$eval('#outliner .node', (n) => n.length);
    ok(nodes > 10, 'hiérarchie : ' + nodes + ' nœuds');
    await page.click('#palette .card[data-bt="2"]');
    const tool = await page.evaluate(() => __posts.filter((p) => p.name === 'tool').pop());
    ok(tool && tool.d.kind === 'line' && tool.d.template.type === 'wall', 'outil mur (2 clics) envoyé');
    await page.evaluate(() => window.postMessage({ action: 'selection', ids: ['w1'], warnings: ['Exemple d\'avertissement'] }, '*'));
    await page.waitForTimeout(150);
    ok(await page.isVisible('[data-oi="0"]'), 'inspecteur : ouverture du mur listée');
    await page.click('#palette [data-op="3"]');
    const upd = await page.evaluate(() => __posts.filter((p) => p.name === 'updateElements').pop());
    ok(upd && upd.d.elements[0].params.openings.length === 2 && upd.d.elements[0].params.openings[1].kind === 'porte', 'ajout d\'une porte au mur');
    await page.fill('[data-p="length"]', '8');
    await page.dispatchEvent('[data-p="length"]', 'change');
    await page.waitForTimeout(450);
    const upd2 = await page.evaluate(() => __posts.filter((p) => p.name === 'updateElements').pop());
    ok(upd2 && upd2.d.elements[0].params.length === 8, 'modification de la longueur');
    await page.screenshot({ path: out + '/ui_construction.png' });
    for (const mode of ['decoration', 'interieur', 'terrain', 'urbanisme']) {
        await page.click(`#modes [data-mode="${mode}"]`);
        await page.waitForTimeout(100);
        ok((await page.$$eval('#palette .card', (c) => c.length)) > 0, 'palette ' + mode);
        await page.screenshot({ path: `${out}/ui_${mode}.png` });
    }
    await page.click('#modes [data-mode="decoration"]');
    await page.fill('#catQ', 'palmier');
    await page.waitForTimeout(300);
    const n = await page.$$eval('#palette .card', (c) => c.length);
    ok(n === 3, 'recherche « palmier » : ' + n + ' résultat(s)');
    await page.click('#right .tabs [data-tab="materiaux"]');
    ok((await page.$$eval('.sw', (s) => s.length)) === 20, '20 matériaux du kit architectural');
    await page.screenshot({ path: out + '/ui_materiaux.png' });
    await page.keyboard.press('Control+KeyZ');
    const undo = await page.evaluate(() => __posts.filter((p) => p.name === 'action').pop());
    ok(undo && undo.d.name === 'undo', 'Ctrl+Z → annuler');
    await page.mouse.move(800, 400);
    await page.mouse.down();
    await page.mouse.up();
    const m = await page.evaluate(() => __posts.filter((p) => p.name === 'mouse').map((p) => p.d.t));
    ok(m.includes('down') && m.includes('up'), 'clic dans la vue transmis au jeu');
    await page.keyboard.down('KeyW');
    await page.keyboard.up('KeyW');
    const k = await page.evaluate(() => __posts.filter((p) => p.name === 'key' && p.d.code === 'KeyW'));
    ok(k.length === 2 && k[0].d.down && !k[1].d.down, 'touche caméra transmise');
    await page.evaluate(() => command('export'));
    ok((await page.textContent('#modalTitle')).includes('Exporter'), 'fenêtre d\'export');
    await page.evaluate(() => window.postMessage({ action: 'exported', result: { ok: true, name: 'map_test', path: '/srv/exports/map_test', pieces: 120, files: ['fxmanifest.lua', 'client.lua'], warnings: [] } }, '*'));
    await page.waitForTimeout(100);
    ok((await page.textContent('#exResult')).includes('Export réussi'), 'résultat d\'export affiché');
    await page.screenshot({ path: out + '/ui_export.png' });
    ok(errors.length === 0, 'aucune erreur JavaScript' + (errors.length ? ' : ' + errors.join(' | ') : ''));
    await browser.close();
    console.log(`\nUI : ${fails} échec(s)`);
    process.exit(fails ? 1 : 0);
})();
