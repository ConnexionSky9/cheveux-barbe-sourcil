-- =====================================================================
--  Tests de la logique serveur de rp_animations (exécutés hors jeu, voir run_tests.py)
--  Chaque test part d'un état neuf : joueurs 1, 2 et 3 côte à côte.
-- =====================================================================
Tests = {}
local function T(name, fn) Tests[#Tests + 1] = { name = name, fn = fn } end
local function check(cond, msg) if not cond then error(msg or 'vérification échouée', 2) end end
local function count(name, target) return #Mock.Sent(name, target) end
local function lastNotify(target)
    local l = Mock.Sent('rp_animations:cl:notify', target)
    return l[#l] and l[#l].args[1] or ''
end
local function inviteId(target)
    local l = Mock.Sent('rp_animations:cl:invite', target)
    return l[#l] and l[#l].args[1].id
end
local function setup()
    Mock.AddPlayer(1, 0, 0)
    Mock.AddPlayer(2, 1.5, 0)
    Mock.AddPlayer(3, 0, 1.5)
    Mock.Advance(100)
end
local function prefs(id, adult, dnd) Mock.Call(id, 'rp_animations:sv:prefs', { adult = adult, dnd = dnd }) end
local function invite(from, to, anim, role) Mock.Call(from, 'rp_animations:sv:invite', to, anim or 'slow_classique', role or 'A') end
local function respond(src, id, accept, confirm) Mock.Call(src, 'rp_animations:sv:respond', id, accept, confirm) end
local function sessionOf(id) return RPA.Sessions.Of(id) end

T('Invitation acceptée : session créée avec rôles A/B, démarrage après « prêt » des deux', function()
    setup()
    invite(1, 2)
    local id = inviteId(2)
    check(id, 'invitation non reçue par 2')
    check(count('rp_animations:cl:outgoing', 1) == 1, 'l\'auteur doit voir son invitation envoyée')
    respond(2, id, true)
    local s = sessionOf(1)
    check(s and s == sessionOf(2), 'session absente')
    check(s.A == 1 and s.B == 2, 'rôles incorrects')
    local p1, p2 = Mock.Sent('rp_animations:cl:prepare', 1)[1], Mock.Sent('rp_animations:cl:prepare', 2)[1]
    check(p1.args[1].role == 'A' and p2.args[1].role == 'B', 'prepare : rôles')
    check(count('rp_animations:cl:go') == 0, 'ne doit pas démarrer avant les deux « prêt »')
    Mock.Call(1, 'rp_animations:sv:ready', s.id, true)
    check(count('rp_animations:cl:go') == 0, 'un seul prêt ne suffit pas')
    Mock.Call(2, 'rp_animations:sv:ready', s.id, true)
    check(count('rp_animations:cl:go', 1) == 1 and count('rp_animations:cl:go', 2) == 1, 'go envoyé aux deux')
    check(s.state == 'playing', 'état playing')
end)

T('Rôle B choisi par l\'auteur : les rôles sont inversés', function()
    setup()
    invite(1, 2, 'slow_classique', 'B')
    respond(2, inviteId(2), true)
    local s = sessionOf(1)
    check(s.A == 2 and s.B == 1, 'A doit être l\'invité')
end)

T('Invitation refusée : aucune session, aucune pénalité, l\'auteur est prévenu', function()
    setup()
