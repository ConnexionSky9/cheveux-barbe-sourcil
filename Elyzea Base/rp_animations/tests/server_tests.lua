T('Anti-spam : délai entre deux invitations et limite par minute', function()
    setup()
    invite(1, 2)
    Mock.Call(1, 'rp_animations:sv:cancelInvite')
    Mock.Clear()
    invite(1, 3)
    check(not inviteId(3), 'délai entre invitations non respecté')
    check(lastNotify(1):find('Attends'), 'message de délai')
    local sent = 1
    for _ = 1, 10 do
        Mock.Advance(Config.Invite.Cooldown * 1000 + 50)
        Mock.Clear()
        invite(1, 3)
        if inviteId(3) then sent = sent + 1 end
        Mock.Call(1, 'rp_animations:sv:cancelInvite')
    end
    check(sent <= Config.Invite.MaxPerMinute, 'limite par minute dépassée : ' .. sent)
end)

