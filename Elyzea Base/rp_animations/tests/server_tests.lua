T('Calibrage : refusé sans permission, valeurs hors limites rejetées, enregistré avec permission', function()
    setup()
    Mock.Call(1, 'rp_animations:sv:saveOffset', 'slow_classique', 1, { x = 0.1, y = 0.2, z = 0, h = 10 })
    check(not Mock.kvp.tuning, 'sans permission : rien d\'enregistré')
    Mock.aces['1:rp_animations.admin'] = true
    Mock.Call(1, 'rp_animations:sv:saveOffset', 'slow_classique', 1, { x = 9, y = 0, z = 0, h = 0 })
    check(not Mock.kvp.tuning, 'hors limites')
    Mock.Call(1, 'rp_animations:sv:saveOffset', 'slow_classique', 9, { x = 0, y = 0, z = 0, h = 0 })
    check(not Mock.kvp.tuning, 'étape inexistante')
    Mock.Call(1, 'rp_animations:sv:saveOffset', 'slow_classique', 1, { x = 0.1, y = 0.25, z = 0, h = 10 })
    check(Mock.kvp.tuning and Mock.kvp.tuning:find('0.25'), 'enregistré')
    check(count('rp_animations:cl:tuning', -1) == 1, 'diffusé à tous')
    invite(1, 2)
    respond(2, inviteId(2), true)
    local p = Mock.Sent('rp_animations:cl:prepare', 2)[1].args[1]
    check(p.offsets['1'] and p.offsets['1'].y == 0.25, 'offset calibré transmis aux participants')
end)

