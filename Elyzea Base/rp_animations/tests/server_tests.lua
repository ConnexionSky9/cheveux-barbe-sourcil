T('Charge : 24 couples en même temps puis tout le monde se déconnecte', function()
    for i = 1, 48 do Mock.AddPlayer(i, math.ceil(i / 2) * 10 + (i % 2 == 0 and 1.2 or 0), 0) end
    Mock.Advance(100)
    for i = 1, 47, 2 do
        invite(i, i + 1)
        respond(i + 1, inviteId(i + 1), true)
        local s = sessionOf(i)
        Mock.Call(i, 'rp_animations:sv:ready', s.id, true)
        Mock.Call(i + 1, 'rp_animations:sv:ready', s.id, true)
    end
    local n = 0
    for _ in pairs(RPA.Sessions.list) do n = n + 1 end
    check(n == 24, '24 sessions attendues, ' .. n .. ' trouvées')
    Mock.Advance(5000)
    n = 0
    for _ in pairs(RPA.Sessions.list) do n = n + 1 end
    check(n == 24, 'la surveillance ne doit pas casser de session valide')
    for i = 1, 48 do Mock.Drop(i) end
    check(next(RPA.Sessions.list) == nil and next(RPA.Sessions.of) == nil, 'tout est nettoyé')
    check(next(RPA.Invites.list) == nil, 'aucune invitation restante')
end)

