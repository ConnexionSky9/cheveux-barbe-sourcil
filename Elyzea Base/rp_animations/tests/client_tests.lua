-- =====================================================================
--  Tests de la logique client de rp_animations (natives simulées, voir client_mock.lua)
--  Ils vérifient l'enchaînement des appels (lancer, placer, attacher, nettoyer),
--  pas le rendu visuel : celui-ci ne peut être validé qu'en jeu.
-- =====================================================================
Tests = {}
local function T(name, fn) Tests[#Tests + 1] = { name = name, fn = fn } end
local function check(cond, msg) if not cond then error(msg or 'vérification échouée', 2) end end
local function lastNotify()
    local l = CM.NuiMsgs('notify')
    return l[#l] and l[#l].text or ''
end
local ME = 101

local function startDuo(role, anim)
    CM.FromServer('rp_animations:cl:prepare', { sid = 7, anim = anim or 'slow_classique', role = role, partner = 2, offsets = {} })
    Mock.Advance(300)
    local r = CM.Server('rp_animations:sv:ready')
    check(#r == 1 and r[1].args[2] == true, 'prêt attendu (' .. role .. ')')
    CM.FromServer('rp_animations:cl:go', 7, 1)
    Mock.Advance(100)
end

T('Solo : lancer depuis le menu puis /stopanim', function()
    CM.Nui('play', { id = 'solo_lente' })
    Mock.Advance(100)
    check(CM.anims[ME] and CM.anims[ME].c == 'low_center', 'clip joué')
    check(CM.anims[ME].flag == 1, 'en boucle')
    check(RPA.Current() and RPA.Current().e.id == 'solo_lente', 'animation courante')
    Mock.commands['stopanim']()
    check(not RPA.Current(), 'arrêtée')
    check(CM.anims[ME] == nil, 'clip retiré du personnage')
    local cur = CM.NuiMsgs('current')
    check(cur[#cur].id == nil, 'menu informé de l\'arrêt')
end)

T('Solo : la touche d\'arrêt (commande liée) arrête aussi', function()
    CM.Nui('play', { id = 'solo_festive' })
    Mock.Advance(100)
    Mock.commands['rp_animations_stop']()
    check(not RPA.Current() and CM.anims[ME] == nil, 'arrêtée')
end)

T('Solo : avancer arrête l\'animation (StopOnMove)', function()
    CM.Nui('play', { id = 'solo_lente' })
    Mock.Advance(100)
    CM.pressed[32] = true
    Mock.Advance(50)
    CM.pressed[32] = nil
    check(not RPA.Current(), 'arrêt au mouvement')
end)

T('Solo : fichiers absents → message clair, rien n\'est joué', function()
    CM.missingDicts['anim@amb@nightclub@mini@dance@dance_solo@female@var_a@'] = true
    CM.Nui('play', { id = 'solo_lente' })
    Mock.Advance(100)
    check(not RPA.Current() and CM.anims[ME] == nil, 'rien joué')
    check(lastNotify():find('indisponible'), 'message : ' .. lastNotify())
end)

T('Animation « à créer » : message clair', function()
    CM.Nui('play', { id = 'valse_classique' })
    check(lastNotify():find('à créer'), 'message : ' .. lastNotify())
    check(not RPA.Current(), 'rien joué')
end)

T('Personnage mort ou en véhicule : refusé', function()
    CM.dead = true
    CM.Nui('play', { id = 'solo_lente' })
    Mock.Advance(100)
    check(not RPA.Current(), 'mort')
    CM.dead, CM.vehicle = false, true
    CM.Nui('play', { id = 'solo_lente' })
    Mock.Advance(100)
    check(not RPA.Current(), 'véhicule')
end)

T('Mort pendant une animation solo : arrêt automatique', function()
    CM.Nui('play', { id = 'solo_lente' })
    Mock.Advance(100)
    CM.dead = true
    Mock.Advance(300)
    check(not RPA.Current(), 'arrêtée')
end)

T('Adulte solo : refusé sans l\'option, joué avec', function()
    CM.Nui('play', { id = 'adulte_boite' })
    Mock.Advance(100)
    check(not RPA.Current(), 'refusé sans option')
    CM.Nui('prefs', { adult = true })
    check(#CM.Server('rp_animations:sv:prefs') >= 1, 'préférence envoyée au serveur')
    CM.Nui('play', { id = 'adulte_boite' })
    Mock.Advance(100)
    check(RPA.Current() and RPA.Current().e.id == 'adulte_boite', 'joué avec option')
    CM.Nui('prefs', { adult = false })
    check(not RPA.Current(), 'désactiver l\'option arrête l\'animation adulte')
end)

T('Enchaînement solo cyclique (séduction avec changement de pose)', function()
    CM.Nui('prefs', { adult = true })
    CM.Nui('play', { id = 'adulte_seduction_poses' })
    Mock.Advance(100)
    check(CM.anims[ME].c == 'sexy003', 'pose 1')
    Mock.Advance(6000)
    check(CM.anims[ME].c == 'sexy004', 'pose 2')
    Mock.Advance(12000)
    check(CM.anims[ME].c == 'sexy003', 'retour pose 1')
end)

T('Duo rôle B : marche vers sa place, attache, phase recalée, puis fin propre', function()
    startDuo('B')
    check(CM.walks == 1, 'B marche vers sa place (pas de téléportation)')
    check(CM.attached[ME] and CM.attached[ME].to == 102, 'B attaché à A')
    check(CM.anims[ME] and CM.anims[ME].c == 'mx_couple5_1_b_clip', 'clip du rôle B')
    CM.anims[102] = { d = 'mx_couple5_1_a', c = 'mx_couple5_1_a_clip' }   -- A joue son clip (répliqué)
    Mock.Advance(700)
    check(CM.phaseSet == 0.42, 'phase de B alignée sur A')
    CM.FromServer('rp_animations:cl:ended', 7, 'partenaire', 'Ton ou ta partenaire a arrêté l\'animation')
    check(not RPA.Current(), 'session finie')
    check(CM.attached[ME] == nil, 'détaché')
    check(CM.anims[ME] == nil, 'clip retiré')
end)

T('Duo rôle A : prêt sans bouger, immobile pendant la mise en place, arrêt local immédiat', function()
    CM.FromServer('rp_animations:cl:prepare', { sid = 7, anim = 'slow_classique', role = 'A', partner = 2, offsets = {} })
    Mock.Advance(300)
    check(CM.walks == 0, 'A ne bouge pas')
    check(CM.keys[30] and CM.keys[31], 'déplacements de A bloqués pendant la mise en place')
    CM.FromServer('rp_animations:cl:go', 7, 1)
    Mock.Advance(100)
    check(CM.anims[ME].c == 'mx_couple5_1_a_clip', 'clip du rôle A')
    check(not CM.attached[ME], 'A n\'est pas attaché')
    CM.Nui('stop')
    check(not RPA.Current(), 'arrêt immédiat côté client')
    local s = CM.Server('rp_animations:sv:stop')
    check(#s == 1, 'serveur prévenu')
    CM.keys = {}
    Mock.Advance(100)
    check(not CM.keys[30], 'plus aucun contrôle bloqué après l\'arrêt')
end)

