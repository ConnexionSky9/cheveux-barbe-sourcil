T('Fondu au noir : seulement si choisi, retiré à l\'arrêt', function()
    CM.Nui('prefs', { adult = true })
    startDuo('A', 'adulte_scene_privee')
    CM.FromServer('rp_animations:cl:step', 7, 2)
    Mock.Advance(3000)
    check(#CM.NuiMsgs('fade') == 0, 'pas de fondu sans choix du joueur')
    RPA.Stop('stop')
    CM.server = {}
    -- Cette fois le joueur a coché le fondu en acceptant
    CM.FromServer('rp_animations:cl:invite', { id = 55, anim = 'adulte_scene_privee', label = 'x', from = 'y', adult = true, fade = true, role = 'A' })
    CM.Nui('respond', { id = 55, accept = true, confirmAdult = true, fade = true })
    startDuo('A', 'adulte_scene_privee')
    CM.FromServer('rp_animations:cl:step', 7, 2)
    Mock.Advance(3000)
    local f = CM.NuiMsgs('fade')
    check(#f == 1 and f[1].on == true, 'fondu choisi')
    RPA.Stop('stop')
    f = CM.NuiMsgs('fade')
    check(f[#f].on == false, 'fondu retiré à l\'arrêt')
end)

