    CM.FromServer('rp_animations:cl:invite', { id = 10, anim = 'slow_classique', label = 'Slow', from = 'x', adult = false, role = 'B' })
    Mock.commands['rp_animations_refuse']()
    r = CM.Server('rp_animations:sv:respond')
    check(#r == 2 and r[2].args[2] == false, 'refus envoyé')
end)

T('Invitation adulte : Y ouvre la confirmation, n\'accepte jamais directement', function()
    CM.FromServer('rp_animations:cl:invite', { id = 11, anim = 'adulte_etreinte', label = 'Étreinte', from = 'x', adult = true, role = 'B' })
    Mock.commands['rp_animations_accept']()
    check(#CM.Server('rp_animations:sv:respond') == 0, 'aucune réponse envoyée par la touche')
    check(CM.focus == true, 'menu ouvert sur la confirmation')
    local o = CM.NuiMsgs('open')
    check(o[#o].confirm == 11, 'fenêtre de confirmation demandée')
    CM.Nui('respond', { id = 99, accept = true, confirmAdult = true })
    check(#CM.Server('rp_animations:sv:respond') == 0, 'mauvais identifiant ignoré')
    CM.Nui('respond', { id = 11, accept = true, confirmAdult = true })
    local r = CM.Server('rp_animations:sv:respond')
    check(#r == 1 and r[1].args[3] == true, 'confirmation explicite transmise')
end)

T('Inviter : rôle et cible transmis au serveur', function()
    CM.Nui('invite', { id = 'slow_classique', target = 2, role = 'B' })
    Mock.Advance(100)
    local r = CM.Server('rp_animations:sv:invite')
    check(#r == 1 and r[1].args[1] == 2 and r[1].args[2] == 'slow_classique' and r[1].args[3] == 'B', 'invitation envoyée')
    local near = CM.Nui('nearby')
    check(#near == 1 and near[1].id == 2 and near[1].canInvite, 'joueur proche listé')
end)

T('Menu : ouverture, favoris persistants, fermeture sans contrôles bloqués', function()
    Mock.commands['danses']()
    check(CM.focus == true, 'focus NUI')
    local o = CM.NuiMsgs('open')
    check(#o == 1 and #o[1].catalog.list > 0, 'catalogue envoyé')
    local ids = {}
    for _, e in ipairs(o[1].catalog.list) do ids[e.id] = e end
    check(ids['slow_classique'] and ids['slow_classique'].playable, 'jouable présent')
    check(ids['valse_classique'] and not ids['valse_classique'].playable, '« à créer » présent en grisé')
    CM.Nui('favorite', { id = 'slow_classique', on = true })
    check(Mock.kvp.favorites and Mock.kvp.favorites:find('slow_classique'), 'favori sauvegardé')
    CM.Nui('close')
    check(CM.focus == false, 'focus rendu au jeu')
end)

T('Vérification des fichiers : les fiches dont un clip manque sont marquées', function()
    CM.missingDicts['mx_couple5_1_b'] = true
